const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

// 埋め込むとタグが途中で閉じてしまう文字列がないか確かめる
function checked(code, tag, file) {
  if (new RegExp('</' + tag, 'i').test(code) || (tag === 'script' && code.includes('<!--'))) {
    throw new Error(file + ' に </' + tag + ' または <!-- が含まれているため埋め込めません');
  }
  return code;
}

let html = read('index.html');
// 置換文字列の $ が特別扱いされないよう、置換は関数で行う
html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g,
  (m, href) => '<style>\n' + checked(read(href), 'style', href) + '</style>');
html = html.replace(/<script src="([^"]+)"><\/script>/g,
  (m, src) => '<script>\n' + checked(read(src), 'script', src) + '</script>');
if (/<link rel="stylesheet"|<script src=/.test(html)) throw new Error('埋め込めなかった外部ファイルがあります');
html = html.replace('<head>\n', '<head>\n<!-- Pinball Maker single-file build (generated by tools/build-single.js). Copyright (c) 2026 FUJIYAMA2236, MIT License (full text in the engine script and the help dialog). -->\n');

const out = path.join(root, 'dist', 'pinball-maker.html');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, html);
console.log('wrote dist/pinball-maker.html (' + Math.round(Buffer.byteLength(html) / 1024) + 'KB)');
